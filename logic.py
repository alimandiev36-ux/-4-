# Вариант 1: Проверка на чётность, цикл с кратными 3, функция max_two.

# --- 1. Функция из варианта ---
# Функция max_two(a, b) возвращает большее из двух чисел.
# Она не печатает результат, а только возвращает его через return.
def max_two(a, b):
    if a > b:
        return a
    else:
        return b


# --- 2. Основная программа ---
print("--- Проверка условий ---")
# Запрашиваем число для проверки на чётность/нечётность.
number = int(input("Введите число для проверки на чётность: "))

if number % 2 == 0:
    print(f"Число {number} — чётное.")
else:
    print(f"Число {number} — нечётное.")


print("\n--- Обработка в цикле ---")
# Запрашиваем N для поиска чисел, кратных 3.
n = int(input("Введите N для поиска чисел, кратных 3: "))

if n <= 0:
    print("Ошибка: N должно быть больше нуля.")
else:
    print(f"Числа от 1 до {n}, кратные 3:")
    # Цикл от 1 до N включительно.
    for i in range(1, n + 1):
        # Проверяем, делится ли число на 3 без остатка.
        if i % 3 == 0:
            print(i, end=" ") # Выводим число в одну строку через пробел
    print() # Перенос строки после цикла


print("\n--- Проверка функции max_two ---")
# Вызываем функцию несколько раз с разными аргументами.
print(f"max_two(5, 10) = {max_two(5, 10)}")
print(f"max_two(-3, 3) = {max_two(-3, 3)}")
print(f"max_two(7, 7) = {max_two(7, 7)}")